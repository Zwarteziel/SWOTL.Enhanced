#!/usr/bin/env python3
"""Embed the GLSL shaders from third_party/dosbox-staging-shaders as C strings."""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', 'third_party', 'dosbox-staging-shaders')
out = os.path.join(here, '..', 'src', 'shaders_embedded.inc')
files = [('SH_CRT_HYLLIAN', 'crt-hyllian.glsl'),
         ('SH_VGA_1080P', 'vga-1080p.glsl'),
         ('SH_VGA_1080P_FDS', 'vga-1080p-fake-double-scan.glsl'),
         ('SH_IMAGE_ADJ', 'image-adjustments.glsl')]
with open(out, 'w', newline='\n') as o:
    o.write('/* Generated by tools/embed_shaders.py from third_party/dosbox-staging-shaders (MIT). */\n')
    for name, fn in files:
        text = open(os.path.join(src, fn), encoding='utf-8').read()
        o.write('static const char %s[] =\n' % name)
        for line in text.split('\n'):
            esc = line.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '    ')
            o.write('    "%s\\n"\n' % esc)
        o.write('    ;\n')
print('wrote', out)
